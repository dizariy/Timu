import assert from 'node:assert/strict';
import {validDay,newsDay,defaultNewsFilters,normalizeNewsFilters,matchesNewsFilters,activeFilterCount} from './dist/news-filter.js';
import {normalizeNews} from './dist/news-client.js';
assert.equal(validDay('2026-02-30'),false);
assert.equal(validDay('2024-02-29'),true);
assert.equal(newsDay('2026-10-06T22:00:00Z'),'2026-10-07');
const item={priority:'important',impact:'neutral',addedAt:'2026-10-07T01:00:00Z',publishedAt:'2026-10-06T12:00:00Z'};
assert(matchesNewsFilters(item,defaultNewsFilters()));
assert(matchesNewsFilters(item,{priorities:['important'],from:'2026-10-07',to:'2026-10-07'}));
assert(!matchesNewsFilters({...item,impact:'negative'},{priorities:['urgent'],from:'',to:''}));
assert(!matchesNewsFilters(item,{priorities:['important'],from:'',to:'2026-10-06'}));
assert(!matchesNewsFilters(item,{priorities:[],from:'',to:''}));
assert.equal(activeFilterCount({priorities:['ordinary'],from:'2026-10-01',to:''}),2);
assert.deepEqual(normalizeNewsFilters({impacts:['bad','negative','neutral'],from:'2026-10-07',to:'2026-10-01'}),{priorities:['urgent','ordinary'],from:'',to:''});
assert.deepEqual(normalizeNewsFilters({priorities:[],impacts:['positive']}),{priorities:[],from:'',to:''});
const raw={id:'one',symbol:'ABC',title:'Company event',url:'https://example.com/event',publishedAt:'2026-10-07',impact:'unknown'};
const rows=normalizeNews({news:[raw,raw,{...raw,id:'unsafe',url:'javascript:alert(1)'},{...raw,id:'bad-date',publishedAt:'invalid'}]});
assert.equal(rows.length,1);assert.equal(rows[0].impact,'neutral');assert.equal(rows[0].companyId,'ABC');
const [cached] = normalizeNews({news:[{...raw,id:'rss-existing',priority:'Плановое',title:'ABC Reports Quarterly Financial Results',impact:'neutral'}]});
assert.equal(cached.priority,'important');assert.equal(cached.impact,'neutral');
assert(matchesNewsFilters(cached,normalizeNewsFilters({impacts:['positive']})));
console.log('News UI checks passed: Moscow dates, priority filters, legacy preferences, cached classification, safe links and deduplication.');
